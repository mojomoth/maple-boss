import { createRequire } from "node:module";
const require = createRequire("/Users/jeongyounglee/work/repo/maple-boss/pocs/package.json");
const { chromium } = require("playwright-core");
const BASE = "http://localhost:3100";
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 }, locale: "ko-KR", colorScheme: "dark" })).newPage();
await page.goto(BASE + "/", { waitUntil: "networkidle" });
await page.locator(".card", { has: page.locator(".card-name", { hasText: /^import$/ }) }).click();
await page.click("dialog.confirm .btn--danger");
await page.waitForSelector(".confirm-error", { timeout: 5000 }).catch(() => {});
console.log("delete 'import' ->", await page.locator(".confirm-error").textContent().catch(() => "(none)"));
await page.screenshot({ path: `${out}/undeletable-import-modal.png` });
await page.goto(BASE + "/pocs/boss?q=a&q=b", { waitUntil: "networkidle" });
console.log("/pocs/boss?q=a&q=b ->", (await page.locator("main").textContent()).slice(0, 200));
await page.screenshot({ path: `${out}/pocs-boss-array-q-500.png` });
await page.goto(BASE + "/pocs/party", { waitUntil: "networkidle" });
await page.screenshot({ path: `${out}/pocs-party-saved-no-delete.png`, fullPage: true });
await browser.close();
